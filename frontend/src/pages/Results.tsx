// src/pages/Results.tsx
import { useLocation, useNavigate } from 'react-router-dom';
import { useEffect, useState } from 'react';
import { jsPDF } from 'jspdf';
import { 
  FileText, 
  BarChart3, 
  Menu, 
  X, 
  ChevronLeft,
  Award,
  Briefcase,
  GraduationCap,
  Download,
  BrainCircuit, 
  BookOpen,
  CheckCircle2,
  Zap,
  MessageSquare,
  AlertCircle
} from 'lucide-react';

// --- INTERFACES ---
interface SkillEvidence {
  name: string;
  snippet: string;
}

interface ScoringExplanations {
  skills: string;
  experience: string;
  education: string;
  overall_match: string;
}

interface AnalysisResult {
  filename: string;
  candidate_name: string;
  location?: string;
  location_rating?: string;
  education_rating?: string;
  experience_rating?: string;
  degree: string;
  years_exp: number;
  overall_aps_score: number;
  mode: string; 
  recommendation: string; 
  interview_questions: string[];
  explanations: ScoringExplanations;
  breakdown: {
    semantic_match: number;
    skill_match: number;
    experience_match: number;
    soft_skills_rating: number; 
    major_relevance: number;
  };
  evidence_skills: SkillEvidence[]; 
  ai_gap_analysis: string;
  error?: string;
}

function Results() {
  const location = useLocation();
  const navigate = useNavigate();
  
  const [results, setResults] = useState<AnalysisResult[]>([]);
  const [selectedIndex, setSelectedIndex] = useState(0);
  const [mobileMenuOpen, setMobileMenuOpen] = useState(false);

  useEffect(() => {
    if (location.state && Array.isArray(location.state)) {
      setResults(location.state);
    } else {
      const savedData = localStorage.getItem("lastResults");
      if (savedData) {
        try {
            const parsedData = JSON.parse(savedData);
            if (Array.isArray(parsedData)) setResults(parsedData);
        } catch (e) {
            console.error("Failed to parse saved results:", e);
        }
      }
    }
  }, [location.state]);

  const selectedCandidate = results[selectedIndex];
  useEffect(() => {
    if (selectedIndex >= results.length) {
        setSelectedIndex(0);
    }
    }, [results, selectedIndex]);
  
    const explanations = selectedCandidate?.explanations ?? {
    skills: "No skill explanation available.",
    experience: "No experience explanation available.",
    education: "No education explanation available.",
    overall_match: "No overall match explanation available."
    };

    const breakdown = selectedCandidate?.breakdown ?? {
    semantic_match: 0,
    skill_match: 0,
    experience_match: 0,
    soft_skills_rating: 0,
    major_relevance: 0
    };

    const academicFitScore = Math.min((breakdown.major_relevance || 0) * 10, 100);

    const interviewQuestions = selectedCandidate?.interview_questions ?? [];
    const evidenceSkills = selectedCandidate?.evidence_skills ?? [];

  // --- 🔥 UPDATED: COMPREHENSIVE PDF EXPORT LOGIC ---
  const handleDownloadReport = () => {
    if (!selectedCandidate) return;

    const explanations = selectedCandidate.explanations ?? {
    skills: "No skill explanation available.",
    experience: "No experience explanation available.",
    education: "No education explanation available.",
    overall_match: "No overall match explanation available."
    };

    const breakdown = selectedCandidate.breakdown ?? {
    semantic_match: 0,
    skill_match: 0,
    experience_match: 0,
    soft_skills_rating: 0,
    major_relevance: 0
    };

    const academicFitScore = Math.min((breakdown.major_relevance || 0) * 10, 100);

    const interviewQuestions = selectedCandidate.interview_questions ?? [];
    
    const doc = new jsPDF();
    let y = 20;

    // 1. Header Section
    doc.setFillColor(66, 133, 244);
    doc.rect(0, 0, 210, 45, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(22);
    doc.setFont("helvetica", "bold");
    doc.text("CANDIDATE AUDIT REPORT", 105, 25, { align: "center" });
    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    doc.text(`Generated by ResuLens AI // Mode: ${selectedCandidate.mode}`, 105, 35, { align: "center" });

    // 2. Candidate Overview
    y = 60;
    doc.setTextColor(40, 40, 40);
    doc.setFontSize(18);
    doc.setFont("helvetica", "bold");
    doc.text(selectedCandidate.candidate_name.toUpperCase(), 20, y);
    
    doc.setFontSize(24);
    doc.setTextColor(66, 133, 244);
    doc.text(`${selectedCandidate.overall_aps_score}%`, 170, y + 5, { align: "center" });
    doc.setFontSize(10);
    doc.text("Match Score", 170, y + 12, { align: "center" });

    y += 15;
    doc.setTextColor(100);
    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    doc.text(`Experience: ${selectedCandidate.years_exp} Years | Degree: ${selectedCandidate.degree}`, 20, y);
    doc.text(`File: ${selectedCandidate.filename}`, 20, y + 5);

    // 3. Recommendation & Overall Match
    y += 20;
    doc.setDrawColor(66, 133, 244);
    doc.setLineWidth(0.5);
    doc.line(20, y, 190, y);
    y += 10;
    doc.setTextColor(66, 133, 244);
    doc.setFont("helvetica", "bold");
    doc.text(`RECOMMENDATION: ${selectedCandidate.recommendation}`, 20, y);
    
    y += 7;
    doc.setTextColor(60, 60, 60);
    doc.setFont("helvetica", "italic");
    const overallMatchLines = doc.splitTextToSize(explanations.overall_match, 170);
    doc.text(overallMatchLines, 20, y);
    y += (overallMatchLines.length * 5) + 10;

    // 4. Detailed Assessment Breakdown
    doc.setFont("helvetica", "bold");
    doc.setTextColor(40);
    doc.text("DETAILED ASSESSMENT", 20, y);
    y += 2;
    doc.line(20, y, 190, y);
    y += 8;

    const sections = [
        { label: "Technical Skills", score: breakdown.skill_match, text: explanations.skills },
        { label: "Professional Experience", score: breakdown.experience_match, text: explanations.experience },
        { label: "Education & Qualification", score: academicFitScore, text: explanations.education }
    ];

    sections.forEach(section => {
        doc.setFont("helvetica", "bold");
        doc.text(`${section.label}: ${section.score}%`, 25, y);
        y += 5;
        doc.setFont("helvetica", "normal");
        const lines = doc.splitTextToSize(section.text, 160);
        doc.text(lines, 30, y);
        y += (lines.length * 5) + 8;
    });

    // Check for page overflow
    if (y > 240) { doc.addPage(); y = 20; }

    // 5. Interview Questions
    doc.setFont("helvetica", "bold");
    doc.text("INTERVIEW FOCUS AREAS", 20, y);
    y += 2;
    doc.line(20, y, 190, y);
    y += 8;
    doc.setFont("helvetica", "normal");
    interviewQuestions.forEach((q, i) => {
        doc.text(`${i+1}. ${q}`, 25, y);
        y += 6;
    });

    y += 10;
    
    // 6. Gaps Analysis
    doc.setFont("helvetica", "bold");
    doc.text("IDENTIFIED GAPS", 20, y);
    y += 7;
    doc.setFont("helvetica", "normal");
    const gapLines = doc.splitTextToSize(selectedCandidate.ai_gap_analysis, 170);
    doc.text(gapLines, 20, y);

    doc.save(`ResuLens_Audit_${selectedCandidate.candidate_name}.pdf`);
  };

  if (results.length === 0) return null;

  return (
    <div className="font-sans text-gray-800 bg-[#f8faff] min-h-screen">
      
      {/* NAVBAR */}
      <nav className="flex items-center justify-between px-8 py-4 bg-white sticky top-0 z-50 shadow-sm border-b border-gray-100">
        <div className="flex items-center gap-2 cursor-pointer" onClick={() => navigate('/')}>
          <div className="bg-blue-600 p-1.5 rounded-lg text-white">
            <FileText className="w-5 h-5" />
          </div>
          <span className="text-xl font-bold text-[#2c3e50] tracking-tight">ResuLens</span>
        </div>
        <div className="hidden md:flex items-center gap-8 font-medium text-gray-600">
          <button onClick={() => navigate('/')} className="hover:text-blue-600">Home</button>
          <button className="flex items-center gap-1 text-blue-600 font-semibold bg-blue-50 px-4 py-2 rounded-full">
            <BarChart3 className="w-4 h-4" /> Reports
          </button>
        </div>
        <button className="md:hidden" onClick={() => setMobileMenuOpen(!mobileMenuOpen)}>
          {mobileMenuOpen ? <X /> : <Menu />}
        </button>
      </nav>

      <main className="max-w-7xl mx-auto p-6 md:p-8">
        <div className="flex justify-between items-center mb-8">
            <h1 className="text-3xl font-black text-[#2c3e50] flex items-center gap-2">
                <Award className="text-yellow-500" /> Auditor Insights
            </h1>
            <button onClick={() => navigate('/')} className="text-blue-600 font-medium flex items-center gap-2">
                <ChevronLeft className="w-4 h-4" /> New Batch
            </button>
        </div>

        <div className="grid grid-cols-1 lg:grid-cols-12 gap-8 items-start">
            {/* SIDEBAR */}
            <div className="lg:col-span-4 flex flex-col gap-3 max-h-[750px] overflow-y-auto pr-2 custom-scrollbar">
                {results.map((result, index) => (
                    <div 
                        key={index}
                        onClick={() => setSelectedIndex(index)}
                        className={`p-4 rounded-2xl border transition-all cursor-pointer flex justify-between items-center ${
                            selectedIndex === index ? 'bg-blue-600 border-blue-600 shadow-lg text-white translate-x-1' : 'bg-white border-gray-100 hover:border-blue-200'
                        }`}
                    >
                        <div className="flex items-center gap-3">
                            <div className={`w-8 h-8 rounded-full flex items-center justify-center font-black text-xs ${
                                selectedIndex === index ? 'bg-white text-blue-600' : 'bg-gray-100 text-gray-400'
                            }`}>
                                {index + 1}
                            </div>
                            <h3 className="font-bold text-sm truncate max-w-[150px]">{result.candidate_name}</h3>
                        </div>
                        <div className="text-xl font-black">{Math.round(result.overall_aps_score)}%</div>
                    </div>
                ))}
            </div>

            {/* MAIN PANEL */}
            <div className="lg:col-span-8 space-y-6">
                {selectedCandidate.error ? (
                    <div className="bg-red-50 p-12 rounded-3xl text-center"><AlertCircle className="mx-auto text-red-400 mb-2"/>{selectedCandidate.error}</div>
                ) : (
                    <>
                        {/* RECOMMENDATION HEADER */}
                        <div className="bg-white border-2 border-blue-600 rounded-3xl p-8 shadow-sm relative overflow-hidden">
                            <div className="absolute top-0 right-0 p-6 opacity-10"><Zap className="w-20 h-20 text-blue-600 fill-blue-600" /></div>
                            <div className="relative z-10">
                                <div className="flex justify-between items-center mb-6">
                                    <h2 className="text-4xl font-black text-[#2c3e50] tracking-tighter">{selectedCandidate.candidate_name}</h2>
                                    <div className="text-right">
                                        <div className="text-6xl font-black text-blue-600">{selectedCandidate.overall_aps_score}%</div>
                                        <p className="text-[10px] font-black uppercase text-blue-400 tracking-widest">Match Strength</p>
                                    </div>
                                </div>
                                <div className="inline-block px-4 py-1.5 bg-blue-600 text-white rounded-full text-xs font-black uppercase tracking-widest mb-4">
                                    Verdict: {selectedCandidate.recommendation}
                                </div>
                                <div className="text-xs text-gray-500 font-bold mb-4">
                                Location: {selectedCandidate.location || "Unknown"} · Experience: {selectedCandidate.years_exp ?? 0} years · Degree: {selectedCandidate.degree || "Unknown"}
                                </div>
                                <p className="text-sm text-gray-600 leading-relaxed font-medium mb-6 italic">{explanations.overall_match}</p>
                                <div className="bg-gray-50 p-5 rounded-2xl border border-gray-100">
                                    <h4 className="text-[10px] font-black uppercase tracking-widest text-gray-400 mb-3 flex items-center gap-2"><MessageSquare className="w-3.5 h-3.5" /> Interview Focus Areas</h4>
                                    <ul className="grid grid-cols-1 md:grid-cols-2 gap-2 list-disc list-inside text-xs text-gray-700 font-bold">
                                        {interviewQuestions.map((q, i) => <li key={i}>{q}</li>)}
                                    </ul>
                                </div>
                            </div>
                        </div>

                        {/* DETAILED ASSESSMENT */}
                        <div className="bg-white rounded-3xl border border-gray-100 p-8 shadow-sm">
                            <h3 className="font-black text-gray-400 text-[10px] uppercase tracking-[0.3em] border-b pb-4 mb-8">Detailed Factors</h3>
                            <div className="space-y-10">
                                <div className="group">
                                    <div className="flex items-center gap-2 mb-2">
                                        <Briefcase className="w-4 h-4 text-emerald-600" />
                                        <span className="text-[10px] font-black text-gray-400 uppercase tracking-widest">Experience Fit</span>
                                    </div>
                                    <ProgressBar label="" score={breakdown.experience_match} color="bg-emerald-500" />
                                    <p className="mt-3 text-[12px] text-gray-500 leading-relaxed border-l-2 border-emerald-100 pl-4">{explanations.experience}</p>
                                </div>

                                <div className="group">
                                    <div className="flex items-center gap-2 mb-2">
                                        <BrainCircuit className="w-4 h-4 text-blue-600" />
                                        <span className="text-[10px] font-black text-gray-400 uppercase tracking-widest">Skill Proficiency</span>
                                    </div>
                                    <ProgressBar label="" score={breakdown.skill_match} color="bg-blue-500" />
                                    <p className="mt-3 text-[12px] text-gray-500 leading-relaxed border-l-2 border-blue-100 pl-4">{explanations.skills}</p>
                                </div>

                                <div className="group">
                                    <div className="flex items-center gap-2 mb-2">
                                        <GraduationCap className="w-4 h-4 text-teal-600" />
                                        <span className="text-[10px] font-black text-gray-400 uppercase tracking-widest">Academic Fit</span>
                                    </div>
                                    <div className="flex justify-between items-center mb-1">
                                         <span className="text-xs font-bold text-gray-700">{selectedCandidate.degree}</span>
                                         <BookOpen className="w-4 h-4 text-teal-300" />
                                    </div>
                                    <ProgressBar label="" score={academicFitScore} color="bg-teal-500" />
                                    <p className="mt-3 text-[12px] text-gray-500 leading-relaxed border-l-2 border-teal-100 pl-4">{explanations.education}</p>
                                </div>
                            </div>
                        </div>

                        {/* EVIDENCE & GAPS */}
                        <div className="grid grid-cols-1 md:grid-cols-2 gap-6 pb-12">
                            <div className="bg-green-50 p-6 rounded-3xl border border-green-100">
                                <h3 className="text-[10px] font-black text-green-800 mb-4 uppercase tracking-[0.2em] flex items-center gap-2"><CheckCircle2 className="w-4 h-4" /> Verified Evidence</h3>
                                <div className="space-y-3 overflow-y-auto max-h-[350px] pr-2 custom-scrollbar">
                                    {evidenceSkills.map((skill, idx) => (
                                        <div key={idx} className="bg-white p-4 rounded-2xl border border-green-100 shadow-sm">
                                            <div className="font-black text-xs text-green-700 mb-1">{skill.name}</div>
                                            <p className="text-[10px] text-gray-400 italic font-medium leading-snug">"{skill.snippet}"</p>
                                        </div>
                                    ))}
                                </div>
                            </div>
                            <div className="bg-amber-50 p-6 rounded-3xl border border-amber-100 flex flex-col justify-between">
                                <div>
                                    <h3 className="text-[10px] font-black text-amber-800 mb-4 uppercase tracking-[0.2em] flex items-center gap-2"><AlertCircle className="w-4 h-4" /> Competency Gaps</h3>
                                    <div className="text-gray-700 text-[13px] leading-relaxed font-bold italic whitespace-pre-line">{selectedCandidate.ai_gap_analysis}</div>
                                </div>
                                <button onClick={handleDownloadReport} className="mt-10 w-full bg-gray-900 text-white py-5 rounded-2xl font-black text-[10px] uppercase tracking-[0.2em] flex items-center justify-center gap-2 hover:bg-black transition-all shadow-xl">
                                    <Download className="w-4 h-4" /> Download Complete Audit
                                </button>
                            </div>
                        </div>
                    </>
                )}
            </div>
        </div>
      </main>
    </div>
  );
}

function ProgressBar({ label, score, color, customLabel }: { label: string, score: number, color: string, customLabel?: string }) {
    const safeScore = Math.max(0, Math.min(Number(score) || 0, 100));

    return (
        <div>
            {label && (
                <div className="flex justify-between text-[10px] mb-2">
                    <span className="font-black text-gray-400 uppercase tracking-widest">{label}</span>
                    <span className="font-black text-gray-900">{customLabel || `${Math.round(safeScore)}%`}</span>
                </div>
            )}
            <div className="w-full bg-gray-100 rounded-full h-1.5 overflow-hidden">
                <div className={`h-full transition-all duration-1000 ease-out ${color}`} style={{ width: `${safeScore}%` }}></div>
            </div>
        </div>
    );
}

export default Results;